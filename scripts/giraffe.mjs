#!/usr/bin/env node
import {readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync} from 'node:fs';
import {join, resolve, sep} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const filmsDir = join(root, 'films');
const [command = 'list', slug = 'the-empty-boat'] = process.argv.slice(2);
const available = () => readdirSync(filmsDir, {withFileTypes: true}).filter((e) => e.isDirectory() && existsSync(join(filmsDir, e.name, 'edit.json'))).map((e) => e.name);
const die = (error) => {console.error(`Giraffe: ${error}`); process.exit(1);};
if (command === 'list') {console.log('Films:', available().join(', ') || '(none)'); process.exit(0);}
if (!['studio', 'render', 'validate'].includes(command)) die('Use studio, render, validate, or list.');
if (!/^[a-z0-9][a-z0-9-]*$/.test(slug) || !available().includes(slug)) die(`Film '${slug}' not found. Choices: ${available().join(', ')}`);
const dir = join(filmsDir, slug);
const edit = JSON.parse(readFileSync(join(dir, 'edit.json'), 'utf8'));
const meta = JSON.parse(readFileSync(join(dir, 'film.json'), 'utf8'));
if (meta.slug !== slug) die(`film.json slug must be '${slug}'`);
if (!Number.isFinite(edit.durationSec) || edit.durationSec <= 0 || !Number.isInteger(edit.fps) || edit.fps <= 0 || !Array.isArray(edit.scenes) || !edit.scenes.length) die('Invalid durationSec, fps, or scenes.');
if (!existsSync(join(dir, edit.audio))) die(`Audio file not found: ${edit.audio}`);
let previousEnd = 0;
const used = new Set();
for (const [i, shot] of edit.scenes.entries()) {
  if (!shot.id || used.has(shot.id)) die(`Invalid or repeated shot id at index ${i}`);
  used.add(shot.id);
  if (Math.abs(shot.startSec - previousEnd) > 0.05 || !(shot.endSec > shot.startSec)) die(`Timing gap/overlap at ${shot.id}: expected ~${previousEnd}, got ${shot.startSec}`);
  if (!shot.image && !shot.video) die(`Missing media source in ${shot.id}`);
  const source = shot.video || shot.image;
  if (source.startsWith('/') || source.split(/[\\/]/).includes('..') || !existsSync(join(dir, source))) die(`Missing or unsafe media in ${shot.id}: ${source}`);
  if (shot.crossfadeFrames && shot.crossfadeFrames > Math.round((shot.endSec - shot.startSec) * edit.fps)) die(`Fade exceeds scene length in ${shot.id}`);
  previousEnd = shot.endSec;
}
if (Math.abs(previousEnd - edit.durationSec) > 0.05) die(`Last scene ends at ${previousEnd} but film duration is ${edit.durationSec}`);
console.log(`Validated '${meta.title}': ${edit.scenes.length} shots, ${edit.durationSec}s, ${edit.width}x${edit.height}@${edit.fps}.`);
if (command === 'validate') process.exit(0);
// A generated import selector is the ONLY generated project source. All film content/media stays in films/<slug>/.
writeFileSync(join(root, 'src', 'selected-film.ts'), `// AUTO-GENERATED by scripts/giraffe.mjs. Do not edit.\nimport edit from '../films/${slug}/edit.json';\nimport film from '../films/${slug}/film.json';\nexport {edit, film};\n`);
const executable = join(root, 'node_modules', '.bin', process.platform === 'win32' ? 'remotion.cmd' : 'remotion');
if (!existsSync(executable)) die('Dependencies missing. Run npm install first.');
const args = command === 'studio'
  ? ['studio', 'src/index.ts', '--public-dir', dir]
  : ['render', 'src/index.ts', 'GiraffeFilm', join(dir, 'output', `${slug}.mp4`), '--codec=h264', '--public-dir', dir];
if (command === 'render') mkdirSync(join(dir, 'output'), {recursive: true});
const result = spawnSync(executable, args, {cwd: root, stdio: 'inherit'});
process.exit(result.status ?? 1);
